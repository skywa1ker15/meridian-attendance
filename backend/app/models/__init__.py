class User(UUIDPrimaryKeyMixin, TimestampMixin, Base):
    __tablename__ = "users"
    __table_args__ = (
        CheckConstraint(f"role IN {_in(E.ROLES)}", name="role_valid"),
        CheckConstraint(f"status IN {_in(E.USER_STATUSES)}", name="status_valid"),
    )
