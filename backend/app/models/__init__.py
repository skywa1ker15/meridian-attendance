    phone: Mapped[str | None] = mapped_column(String(32))
    department_id: Mapped[uuid.UUID | None] = mapped_column(ForeignKey("departments.id", ondelete="RESTRICT"), index=True)
    role: Mapped[str] = mapped_column(String(20), nullable=False, default="employee", server_default="employee")
    status: Mapped[str] = mapped_column(String(20), nullable=False, default="active", server_default="active", index=True)
    password_hash: Mapped[str | None] = mapped_column(String(255))
    must_change_password: Mapped[bool] = mapped_column(Boolean, nullable=False, default=False, server_default=text("false"))
    token_version: Mapped[int] = mapped_column(Integer, nullable=False, default=1, server_default="1")
    failed_login_attempts: Mapped[int] = mapped_column(Integer, nullable=False, default=0, server_default="0")
    locked_until: Mapped[datetime | None] = mapped_column(DateTime(timezone=True))
    last_login_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True))
    deactivated_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True))
    deactivation_reason: Mapped[str | None] = mapped_column(Text)
    notification_push: Mapped[bool] = mapped_column(Boolean, nullable=False, default=True, server_default=text("true"))
    erased_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True))

    department: Mapped[Department | None] = relationship(back_populates="users")
    devices: Mapped[list["Device"]] = relationship(back_populates="user", foreign_keys="Device.user_id")

    @property
    def full_name(self) -> str:
        return f"{self.first_name} {self.last_name}".strip()


